# Module: scripts/ci/render-compute-egress-allowlist.sh
# Purpose: Render the per-env substrate admission file consumed by
#          infra/provision/cherry/harden-docker-public-ports.sh: full-line `#`
#          comments + one `CIDR:port,port` allow line per grant.
#
# task.5428 — provider egress CIDRs are retired. Every Akash lane reaches the
# shared substrate over its env mesh, so no provider NAT is admitted through
# the VM firewall and the catalog carries no `compute_egress_cidrs`. The one
# remaining grant is the native migration custodian (task.5256): migration Jobs
# for an Akash-placed nonproduction lane run on the production control cluster
# and dial that lane's own Postgres on TCP5432. Every other env renders an
# allow-free file, which the harden script treats as fail-closed (public DROP
# stays, no ACCEPTs). The file name and install path are kept so the next
# hardener run replaces the old provider rows on every VM.
#
# Pure render: reads the catalog, writes stdout. No state mutation. Idempotent
# and deterministic.
#
# Usage: render-compute-egress-allowlist.sh <lane> [destination-env]
# Env:   COGNI_CATALOG_ROOT — override catalog dir (tests; same knob as
#        scripts/ci/lib/image-tags.sh).
# Links: task.5428, task.5256, task.5052, bug.5191

set -euo pipefail

ENV_NAME="${1:?usage: render-compute-egress-allowlist.sh <env>}"
DESTINATION_ENV="${2:-$ENV_NAME}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
CATALOG_ROOT="${COGNI_CATALOG_ROOT:-$REPO_ROOT/infra/catalog}"

command -v yq >/dev/null 2>&1 || { echo "[render-compute-egress] ERROR: yq is required" >&2; exit 1; }
[ -d "$CATALOG_ROOT" ] || { echo "[render-compute-egress] ERROR: catalog root not found: $CATALOG_ROOT" >&2; exit 1; }

# ONE placement reader for the whole shell lane — deployment_provider_for_target()
# is the same resolver render-scheduler-worker-endpoints.sh and reconcile-node-dns.sh
# use, so the firewall can never disagree with where the workload was actually sent.
# shellcheck source=scripts/ci/lib/image-tags.sh
source "$SCRIPT_DIR/lib/image-tags.sh"
# shellcheck source=scripts/ci/lib/appset-paths.sh
source "$SCRIPT_DIR/lib/appset-paths.sh"
# shellcheck source=scripts/ci/lib/lane-db-residency.sh
source "$SCRIPT_DIR/lib/lane-db-residency.sh"
# shellcheck source=scripts/setup/lib/cogni-deployment-identity.sh
source "$REPO_ROOT/scripts/setup/lib/cogni-deployment-identity.sh"

echo "# GENERATED by scripts/ci/render-compute-egress-allowlist.sh from infra/catalog/*.yaml — do not hand-edit."
echo "# env: ${DESTINATION_ENV} — no provider egress CIDRs (task.5428: lanes reach the substrate over the mesh). Empty list = fail-closed."

migration_control_needed=false
source_envs=("$DESTINATION_ENV")
[[ "$ENV_NAME" == "$DESTINATION_ENV" ]] || source_envs+=("$ENV_NAME")
# The installed file replaces every managed grant on this VM. A custodian grant
# is only ever owned by the destination lane itself, never by a foreign caller.
for SOURCE_ENV in "${source_envs[@]}"; do
for catalog_file in "$CATALOG_ROOT"/*.yaml; do
  [ -e "$catalog_file" ] || continue
  row_name="$(yq -N '.name // ""' "$catalog_file")"

  # Only rows deployed to this env contribute (deploy ⊆ provisioned).
  yq -N -e ".envs // [] | contains([\"$SOURCE_ENV\"])" "$catalog_file" >/dev/null 2>&1 || continue

  # …and only where THIS env's placement is off-cluster (bug.5191). A row present
  # in the env under k3s runs its migrations inside the VM's own cluster.
  provider="$(deployment_provider_for_target "$row_name" "$SOURCE_ENV")" || {
    echo "[render-compute-egress] ERROR: unresolvable deployment_provider for '$row_name' in env '$SOURCE_ENV' ($catalog_file)" >&2
    exit 1
  }
  [ "$provider" = "akash" ] || continue

  # Native migration Jobs run on the custodian, while Postgres is lane-local.
  # This is down-trust only: never admit a nonproduction client to production.
  case "$SOURCE_ENV" in
    candidate-*|preview)
      control_env="$(CATALOG_DIR="$CATALOG_ROOT" control_env_for "$SOURCE_ENV" "$row_name")" || exit 1
      postgres_env="$(CATALOG_DIR="$CATALOG_ROOT" lane_db_vm_env "$row_name" "$SOURCE_ENV")" || exit 1
      if [ "$DESTINATION_ENV" = "$SOURCE_ENV" ] && [ "$control_env" = production ] && [ "$control_env" != "$SOURCE_ENV" ] && [ "$postgres_env" = "$SOURCE_ENV" ]; then
        migration_control_needed=true
      fi
      ;;
  esac
done
done

if "$migration_control_needed"; then
  # Never derive foreign trust from cogni_domain_root's DAO fallback.
  [ -n "${FORK_DOMAIN_ROOT:-}" ] || {
    echo "[render-compute-egress] ERROR: explicit FORK_DOMAIN_ROOT is required for foreign migration custody" >&2
    exit 1
  }
  control_host="$(cogni_vm_host_for_env production "$FORK_DOMAIN_ROOT" "$(cogni_deployment_slug)")"
  control_addresses="$(_lane_db_resolve_a "$control_host")" || {
    echo "[render-compute-egress] ERROR: cannot resolve migration custodian $control_host" >&2
    exit 1
  }
  if [ "$(printf '%s\n' "$control_addresses" | awk 'NF {n++} END {print n+0}')" != 1 ] ||
    ! printf '%s\n' "$control_addresses" | awk -F. '
      NF != 4 {exit 1}
      {for (i=1;i<=4;i++) if ($i !~ /^[0-9]+$/ || $i > 255) exit 1;
       if ($1 == 0 || $1 == 127 || $1 >= 224) exit 1}'; then
    echo "[render-compute-egress] ERROR: migration custodian must resolve to exactly one usable IPv4: $control_host" >&2
    exit 1
  fi
  echo "# migration custodian: ${control_host} -> ${DESTINATION_ENV} Postgres only (task.5256)"
  echo "${control_addresses}/32:5432"
fi
